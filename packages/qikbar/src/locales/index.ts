/** Every bundled locale, by language code. */
export const locales: Record<string, Labels> = { en, es, fr, de, pt, it, nl, ja, zh, ko }

/** Pick the best bundled locale for a language tag (e.g. `navigator.language`). Falls back to English. */
export function localeFor(tag: string | undefined = typeof navigator !== 'undefined' ? navigator.language : undefined): Labels {
  if (!tag) return en
  const lang = tag.toLowerCase().split(/[-_]/)[0]!
  return locales[lang] ?? en
}
